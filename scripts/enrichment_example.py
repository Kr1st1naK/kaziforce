"""
Worked enrichment example for the thesis (Chapter 5 evidence).

Takes one base-profile group from the development split and shows its
known_alias profile before and after knowledge-graph enrichment: the text, the
informal term matched, the occupation it maps to, and every inferred skill with
the graph path that produced it. A contrast table shows all variants of the
group under ProfileEnricher and NullEnricher.

Writes docs/evidence/enrichment_example.md.
Usage: python scripts/enrichment_example.py [--group G0004]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from kaziforce_api.data.data_loader import DataLoader
from kaziforce_api.data.loaders import load_synthetic_ground_truth
from kaziforce_api.provenance import git_commit, has_uncommitted_changes
from kaziforce_kg.builder import KnowledgeGraphBuilder
from kaziforce_kg.enrichment import NullEnricher, ProfileEnricher

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "docs/evidence/enrichment_example.md"
VARIANT_ORDER = ("formal", "known_alias", "held_out", "minimal")


def table(header: list[str], rows: list[list]) -> list[str]:
    return [f"| {' | '.join(header)} |", "|" + "---|" * len(header)] + [f"| {' | '.join(map(str, r))} |" for r in rows]


def main(group: str) -> str:
    kg = KnowledgeGraphBuilder().build()
    enricher, null = ProfileEnricher(kg), NullEnricher()
    loader = DataLoader()
    truth = load_synthetic_ground_truth()["worker_truth"]
    members = truth[truth.group_id == group]
    if members.empty or set(members.split) != {"development"}:
        raise SystemExit(f"{group} is not a development-split group")
    workers = {w.worker_id: w for w in loader.workers("development")}
    by_variant = {r.variant: workers[r.worker_id] for r in members.itertuples()}
    w = by_variant["known_alias"]
    e = enricher.enrich(w.biography, w.skills)

    def show(path):
        return " → ".join([kg.label(path[0][0])] + [f"*{rel}* → {kg.label(v)}" for _, rel, v in path])

    occupation = e.occupations[0]
    lines = ["# Worked enrichment example", "",
             f"Generated by `scripts/enrichment_example.py --group {group}` from commit `{git_commit()[:7]}`"
             + (" **with uncommitted changes**" if has_uncommitted_changes() else "") + ". "
             "Development split. Group IDs and variants are dataset bookkeeping; the enricher sees only the profile.",
             "", "## Before enrichment (known_alias profile)", "",
             *table(["Field", "Value"], [["worker_id", f"`{w.worker_id}`"], ["biography", w.biography],
                                         ["skills", ", ".join(w.skills)], ["location", w.location],
                                         ["availability", w.availability], ["rate_expectation (KES/day)", w.rate_expectation]]),
             "", "## After enrichment (ProfileEnricher)", "",
             *table(["Step", "Result"], [
                 ["Informal term matched", ", ".join(f"{kg.label(t)} (`{t}`)" for t in e.terms)],
                 ["MAPS_TO occupation", f"{kg.label(occupation)} (ESCO {kg.graph.nodes[occupation]['isco_code']}, "
                                        f"`{occupation}`)"],
                 ["Skills inferred", f"{len(e.inferred_skills)} essential skills of {kg.label(occupation)}"],
                 ["Stated skills mapped", len(e.stated_skills)], ["Unmapped text", ", ".join(e.unmapped) or "none"]]),
             "", "### Inferred skills, each with the graph path that produced it", "",
             *table(["#", "Skill", "ESCO URI", "Graph path"],
                    [[i, ev.label, f"`{ev.skill}`", show(ev.path)] for i, ev in enumerate(e.evidence, start=1)]),
             "", "### Figure", "", "```mermaid", "flowchart LR",
             f'  T["{kg.label(e.terms[0])}<br/>(InformalTerm)"] -- MAPS_TO --> O["{kg.label(occupation)}<br/>(Occupation)"]',
             *[f'  O -- {ev.path[-1][1]} --> S{i}["{ev.label}"]' for i, ev in enumerate(e.evidence, start=1)],
             "```", "", "## The same group under both enrichers", "",
             "All variants share the base profile; only the wording differs. NullEnricher is the "
             "no-knowledge-graph configuration: it keeps listed skills as literal text and maps nothing.", "",
             *table(["Variant", "Skills listed", "KG: occupation", "KG: stated (mapped or literal)", "KG: inferred", "KG: unmapped",
                     "No KG: skills (all literal text)"],
                    [[v, ", ".join(p.skills[:2]) + (" …" if len(p.skills) > 2 else ""),
                      ", ".join(kg.label(o) for o in r.occupations) or "none", len(r.stated_skills), len(r.inferred_skills),
                      ", ".join(r.unmapped) or "none", len(null.enrich(p.biography, p.skills).skills)]
                     for v in VARIANT_ORDER if v in by_variant
                     for p in [by_variant[v]] for r in [enricher.enrich(p.biography, p.skills)]]),
             ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--group", default="G0004", help="development-split group (default: an electrician group)")
    print(main(parser.parse_args().group))
