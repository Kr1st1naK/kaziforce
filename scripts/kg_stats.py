"""
Knowledge graph statistics for the thesis (Chapter 5 evidence).

Builds the graph exactly as the recommendation engine does and writes node and
edge counts by type, the schema triples, the per-occupation skill counts, the
informal-term mappings and the withheld-alias check.

Writes docs/evidence/kg_stats.md. Usage: python scripts/kg_stats.py
"""

from __future__ import annotations

import json
from pathlib import Path

from kaziforce_api.provenance import git_commit, has_uncommitted_changes
from kaziforce_kg.builder import KnowledgeGraphBuilder
from kaziforce_kg.graph import HAS_ESSENTIAL_SKILL, HAS_OPTIONAL_SKILL, INFORMAL_TERM, OCCUPATION

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "docs/evidence/kg_stats.md"


def table(header: list[str], rows: list[list]) -> list[str]:
    return [f"| {' | '.join(header)} |", "|" + "---|" * len(header)] + [f"| {' | '.join(map(str, r))} |" for r in rows]


def main() -> str:
    builder = KnowledgeGraphBuilder()
    kg = builder.build()
    g, stats = kg.graph, kg.stats()
    occupations = sorted((n for n, d in g.nodes(data=True) if d["type"] == OCCUPATION), key=kg.label)
    terms = sorted((n for n, d in g.nodes(data=True) if d["type"] == INFORMAL_TERM), key=kg.label)
    terms_of = {o: [kg.label(t) for t in terms if kg.occupation_of(t) == o] for o in occupations}
    held_out = builder.vocabulary.held_out_terms()
    kg_manifest = json.loads((builder.kg_dir / "manifest.json").read_text())

    def count(o, relation):
        return sum(1 for _, _, r in g.out_edges(o, data="relation") if r == relation)

    lines = ["# Knowledge graph statistics", "",
             f"Generated by `scripts/kg_stats.py` from commit `{git_commit()[:7]}`"
             + (" **with uncommitted changes**" if has_uncommitted_changes() else "") + ".",
             f"Graph: `networkx.DiGraph`, {stats['total_nodes']} nodes, {stats['total_edges']} edges. "
             f"ESCO subset downloaded {kg_manifest['esco']['subset_downloaded_at'][:10]}; "
             f"broader-concept labels fetched {kg_manifest['esco']['broader_labels_fetched_at'][:10]}.", "",
             "## Nodes by type", "", *table(["Type", "Count"], [[t, n] for t, n in stats["nodes"].items()]), "",
             "## Edges by relation", "", *table(["Relation", "Count"], [[r, n] for r, n in stats["edges"].items()]), "",
             "## Schema (source type, relation, target type)", "",
             *table(["Triple", "Count"], [[t, n] for t, n in stats["triples"].items()]), "",
             "## Occupations", "",
             *table(["Occupation", "ESCO code", "Essential skills", "Optional skills", "Informal terms (MAPS_TO)"],
                    [[kg.label(o), g.nodes[o]["isco_code"], count(o, HAS_ESSENTIAL_SKILL), count(o, HAS_OPTIONAL_SKILL),
                      ", ".join(terms_of[o]) or "—"] for o in occupations]), "",
             "## Withheld aliases", "",
             "Accepted aliases deliberately kept out of the graph for the unseen-term condition. The builder refuses "
             "to build if any node's label or normalised key equals one of these keys.", "",
             *table(["Alias", "Normalised key", "In graph?"],
                    [[t["alias"], t["normalized"], "yes" if f"term:{t['normalized']}" in g else "no"] for t in held_out]),
             ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    return "\n".join(lines)


if __name__ == "__main__":
    print(main())
