"""
Worked explanation example for the thesis (Chapter 5 evidence).

The interface shows a worker plain sentences only, so there is no screenshot that
carries the structured evidence behind them. This script records that evidence
directly from the generator: for one development-split worker, the full
explanation payload the API returns for their top match -- every reason, its
provenance, the graph path behind it, the criterion scores, and what could not be
assessed -- together with the coverage flags of docs/scoring-policy.md §7.

Writes docs/evidence/explanation_payload.md.
Usage: python scripts/explanation_example.py [--variant known_alias] [--rank 1]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from kaziforce_api.data.data_loader import DataLoader
from kaziforce_api.explainability.explain import ExplanationGenerator
from kaziforce_api.matching.semantic import SemanticScorer, job_text
from kaziforce_api.pipeline import build_recommender
from kaziforce_api.provenance import git_commit, has_uncommitted_changes
from kaziforce_kg.builder import KnowledgeGraphBuilder

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "docs/evidence/explanation_payload.md"

KIND_NOTE = {
    "graph_skill": "reached through the knowledge graph",
    "literal_skill": "the worker's own words, matched directly",
    "criterion": "a rule criterion that was assessed and scored above zero",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--variant", default="known_alias")
    parser.add_argument("--rank", type=int, default=1)
    args = parser.parse_args()

    loader = DataLoader()
    jobs, kg = loader.jobs(), KnowledgeGraphBuilder().build()
    semantic = SemanticScorer()
    recommender = build_recommender("full", jobs, kg=kg, semantic=semantic)
    semantic.embed([job_text(j) for j in recommender.jobs])

    variants = loader.variants()
    worker = next(w for w in loader.workers("development") if variants[w.worker_id] == args.variant)
    match = recommender.rank(worker, k=args.rank)[args.rank - 1]
    posting = next(j for j in jobs if j.posting_id == match.posting_id)
    explanation = ExplanationGenerator(kg).explain(worker, posting, match)
    payload = explanation.to_dict()

    lines = [
        "# A full explanation payload",
        "",
        "Evidence for Chapter 5. The interface shows a worker the sentences only, so this is",
        "where the structured evidence behind them is recorded: the provenance of every matched",
        "skill, the graph path that produced it, the criteria that were assessed, and what could",
        "not be. It is the `explanation` object the API returns on every result of",
        "`POST /recommend`, verbatim.",
        "",
        f"Generated by `scripts/explanation_example.py` at commit `{git_commit()[:7]}`"
        + (" **with uncommitted changes**" if has_uncommitted_changes() else "")
        + f", from the frozen development split (variant `{args.variant}`, rank {args.rank}).",
        "",
        "## The worker",
        "",
        f"- Wording: *\"{worker.biography}\"*",
        f"- Listed skills: {', '.join(worker.skills) if worker.skills else '*none*'}",
        f"- Location: {worker.location or '*not stated*'} · Availability: {worker.availability or '*not stated*'}"
        f" · Rate: {f'KES {worker.rate_expectation:,.0f}' if worker.rate_expectation is not None else '*not stated*'}",
        "",
        "## The posting",
        "",
        f"- Title: **{posting.title}**",
        f"- Required skills: {', '.join(posting.required_skills) if posting.required_skills else '*none stated*'}",
        f"- Location: {posting.location or '*not stated*'} · Availability: {posting.availability or '*not stated*'}"
        f" · Budget: {f'KES {posting.budget:,.0f}' if posting.budget is not None else '*not stated*'}",
        "",
        "## What the worker sees",
        "",
        "These sentences, and nothing else. No component score, no criterion table, no raw path.",
        "",
        *(f"- {line}" for line in explanation.text),
        "",
    ]
    if explanation.not_assessed:
        lines += ["Followed by what could not be checked:", "",
                  *(f"- {line}" for line in explanation.not_assessed), ""]

    lines += [
        "## The reasons, and the evidence behind each",
        "",
        "| # | Kind | Sentence | Provenance | Evidence |",
        "|---|---|---|---|---|",
    ]
    for i, reason in enumerate(explanation.reasons, start=1):
        if reason.kind == "criterion":
            evidence = f"`{reason.criterion}` scored {reason.score:.2f}"
            provenance = "—"
        else:
            provenance = f"`{reason.source}`"
            evidence = (" → ".join(
                [f"*{kg.label(reason.graph_path[0][0])}*"]
                + [f"**{relation}** → {kg.label(target)}" for _, relation, target in reason.graph_path])
                if reason.graph_path else "listed by the worker, no inference needed")
        lines.append(f"| {i} | `{reason.kind}` | {reason.text} | {provenance} | {evidence} |")

    lines += [
        "",
        "Kinds: " + "; ".join(f"`{k}` — {v}" for k, v in KIND_NOTE.items()) + ".",
        "",
        "## Coverage (docs/scoring-policy.md §7)",
        "",
        f"- **Covered (the NFR-02 rule, a shared skill is required): {explanation.covered}**",
        f"- Covered under the inclusive rule (any concrete reason): {explanation.covered_inclusive}",
        f"- Covered by a graph-traced skill: {explanation.covered_graph}",
        "",
        "## The payload, verbatim",
        "",
        "```json",
        json.dumps(payload, indent=2),
        "```",
        "",
        "## Scores, for completeness",
        "",
        "Shown here, not to the worker: a component score is not something anyone can check.",
        "",
        f"- Composite {match.composite:.3f} · rule {match.rule:.3f} · semantic {match.semantic:.3f}",
        "- Criteria: " + ", ".join(
            f"{name} = {'not assessed' if value is None else f'{value:.2f}'}"
            for name, value in match.components.items()),
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Written to {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
