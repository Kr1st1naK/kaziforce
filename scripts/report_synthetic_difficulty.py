"""
Difficulty report for the synthetic dataset (report only; nothing is tuned on it).

1. Pairwise skill overlap between areas: Jaccard similarity of the ESCO skill
   pools (essential + optional) of each area's selected occupations.
2. Keyword baseline on DEVELOPMENT workers only: each worker (biography +
   skills) is compared with every job (title + description + required skills)
   by the number of shared content words. Reports how often a relevant job is
   ranked first, per variant:
     strict    a relevant job has the single highest score
     expected  ties broken at random (share of relevant jobs among the tied top)
   once against synthetic jobs only and once with the Job Skill Set distractors.

Writes data/raw/synthetic/difficulty_report.md.

Usage: python scripts/report_synthetic_difficulty.py
"""

from __future__ import annotations

import json
import re
from itertools import combinations
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
DATA = REPO_ROOT / "data/raw/synthetic"
OUT = DATA / "difficulty_report.md"
STOPWORDS = set("""a an and are as at be by for from has have i in is it of on or our per the to we who with
will can should your you my am years year yrs day work based available experience experienced kes ksh
ni na wa ya kwa za la mimi niko nina hapa kazi miaka siku""".split())


def md_table(df: pd.DataFrame) -> str:
    """Markdown table without the optional tabulate dependency."""
    cols = list(df.columns)
    rows = [" | ".join(str(v) for v in r) for r in df.itertuples(index=False)]
    return "\n".join([f"| {' | '.join(cols)} |", "|" + "---|" * len(cols)] + [f"| {r} |" for r in rows])


def tokens(text: str) -> set[str]:
    return {t for t in re.findall(r"[a-z]+", text.lower()) if len(t) > 2 and t not in STOPWORDS}


def area_overlap(pools: pd.DataFrame) -> pd.DataFrame:
    sets = pools.groupby("area_id")["skill_label"].apply(set)
    names = pools.groupby("area_id")["esco_label"].apply(lambda s: " / ".join(sorted(set(s))))
    rows = []
    for a, b in combinations(sorted(sets.index, key=int), 2):
        inter, union = sets[a] & sets[b], sets[a] | sets[b]
        rows.append({"area_a": a, "area_b": b, "shared": len(inter), "jaccard": round(len(inter) / len(union), 3)})
    return pd.DataFrame(rows).sort_values("jaccard", ascending=False), names


def keyword_top1(workers, jobs, relevant: set[tuple[str, str]]) -> pd.DataFrame:
    job_tokens = {j.posting_id: tokens(f"{j.title} {j.description} {' '.join(j.required_skills)}")
                  for j in jobs.itertuples()}
    rows = []
    for w in workers.itertuples():
        wt = tokens(f"{w.biography} {' '.join(w.skills)}")
        scores = {pid: len(wt & jt) for pid, jt in job_tokens.items()}
        best = max(scores.values())
        top = [pid for pid, s in scores.items() if s == best]
        rel_top = [pid for pid in top if (w.worker_id, pid) in relevant]
        rows.append({"variant": w.variant, "strict": int(len(top) == 1 and len(rel_top) == 1),
                     "expected": len(rel_top) / len(top), "zero_overlap": int(best == 0)})
    return pd.DataFrame(rows).groupby("variant").agg(
        workers=("strict", "size"), strict=("strict", "mean"), expected=("expected", "mean"),
        zero_overlap=("zero_overlap", "mean")).round(3)


def main() -> None:
    workers = pd.read_csv(DATA / "workers.csv", dtype=str, keep_default_na=False)
    jobs = pd.read_csv(DATA / "jobs.csv", dtype=str, keep_default_na=False)
    workers["skills"] = workers["skills"].apply(json.loads)
    jobs["required_skills"] = jobs["required_skills"].apply(json.loads)
    truth = pd.read_csv(DATA / "ground_truth/worker_truth.csv", dtype=str)
    rel = pd.read_csv(DATA / "ground_truth/relevance.csv", dtype=str)
    pools = pd.read_csv(DATA / "inputs/area_skill_pools.csv", dtype=str)
    relevant = set(zip(rel.worker_id, rel.posting_id))

    dev_ids = set(truth[truth.split == "development"].worker_id)
    dev = workers[workers.worker_id.isin(dev_ids)]
    overlap, names = area_overlap(pools)
    synthetic_only = keyword_top1(dev, jobs[jobs.source == "synthetic"], relevant)
    with_distractors = keyword_top1(dev, jobs, relevant)

    lines = ["# Synthetic dataset: difficulty report", "",
             "Generated by `scripts/report_synthetic_difficulty.py`. Report only: nothing was tuned on it.", "",
             "## Pairwise skill overlap between areas", "",
             "Jaccard similarity of the ESCO skill pools (essential + optional) of each area's selected occupations.",
             "Area names: " + "; ".join(f"{a} = {names[a]}" for a in sorted(names.index, key=int)) + ".", "",
             md_table(overlap.head(15)), "",
             f"{(overlap.shared > 0).sum()} of {len(overlap)} area pairs share at least one skill; "
             f"median Jaccard {overlap.jaccard.median():.3f}, maximum {overlap.jaccard.max():.3f}.", "",
             "## Keyword overlap baseline, development workers", "",
             "Share of development workers whose top-ranked job (by shared content words) is relevant.", "",
             "### Against the 80 synthetic jobs", "", md_table(synthetic_only.reset_index()), "",
             "### Against all jobs (synthetic + Job Skill Set distractors)", "", md_table(with_distractors.reset_index()), ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
